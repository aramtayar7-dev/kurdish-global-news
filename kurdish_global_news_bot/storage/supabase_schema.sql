-- ============================================================================
-- Kurdish Global News Bot — Supabase PostgreSQL Schema
-- Run this script once in the Supabase SQL Editor before enabling
-- SUPABASE_URL and SUPABASE_KEY in GitHub Actions or cloud deployments.
-- ============================================================================

-- 1. Articles Table
CREATE TABLE IF NOT EXISTS articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_url TEXT NOT NULL UNIQUE,
    url_hash TEXT NOT NULL DEFAULT '',
    original_url TEXT NOT NULL,
    original_title TEXT NOT NULL DEFAULT '',
    normalized_title TEXT NOT NULL DEFAULT '',
    translated_title TEXT NOT NULL DEFAULT '',
    original_summary TEXT NOT NULL DEFAULT '',
    translated_summary TEXT NOT NULL DEFAULT '',
    source_name TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL DEFAULT '',
    priority TEXT NOT NULL DEFAULT 'NORMAL',
    importance_score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    publication_date TEXT,
    discovered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processed_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'DISCOVERED',
    content_hash TEXT NOT NULL DEFAULT '',
    event_fingerprint TEXT NOT NULL DEFAULT '',
    retry_count INTEGER NOT NULL DEFAULT 0,
    error_message TEXT NOT NULL DEFAULT '',
    telegram_message_id BIGINT,
    image_url TEXT NOT NULL DEFAULT '',
    country TEXT NOT NULL DEFAULT '',
    region TEXT NOT NULL DEFAULT '',
    named_entities TEXT NOT NULL DEFAULT '',
    is_breaking BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_articles_canonical_url ON articles (canonical_url);
CREATE INDEX IF NOT EXISTS idx_articles_url_hash ON articles (url_hash);
CREATE INDEX IF NOT EXISTS idx_articles_content_hash ON articles (content_hash);
CREATE INDEX IF NOT EXISTS idx_articles_event_fingerprint ON articles (event_fingerprint);
CREATE INDEX IF NOT EXISTS idx_articles_status ON articles (status);
CREATE INDEX IF NOT EXISTS idx_articles_discovered_at ON articles (discovered_at DESC);
CREATE INDEX IF NOT EXISTS idx_articles_published_at ON articles (published_at DESC);
CREATE INDEX IF NOT EXISTS idx_articles_normalized_title ON articles (normalized_title);

-- 2. Skipped URLs Table (low-relevance & duplicate event persistence)
CREATE TABLE IF NOT EXISTS skipped_urls (
    url_hash TEXT PRIMARY KEY,
    canonical_url TEXT NOT NULL,
    title TEXT NOT NULL DEFAULT '',
    score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    reason TEXT NOT NULL DEFAULT '',
    skipped_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_skipped_urls_canonical ON skipped_urls (canonical_url);

-- 3. Daily Digests Table (prevents duplicate nightly digests per Kurdistan UTC+3 date)
CREATE TABLE IF NOT EXISTS daily_digests (
    digest_date TEXT PRIMARY KEY,
    story_count INTEGER NOT NULL DEFAULT 0,
    digest_text TEXT NOT NULL DEFAULT '',
    telegram_message_id BIGINT,
    published_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Sources Table
CREATE TABLE IF NOT EXISTS sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    source_type TEXT NOT NULL DEFAULT '',
    url TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL DEFAULT '',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_checked_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    last_error TEXT NOT NULL DEFAULT '',
    consecutive_failures INTEGER NOT NULL DEFAULT 0
);

-- 5. Events Table
CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_fingerprint TEXT NOT NULL UNIQUE,
    event_title TEXT NOT NULL DEFAULT '',
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    article_count INTEGER NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS idx_events_fingerprint ON events (event_fingerprint);

-- 6. System Logs Table
CREATE TABLE IF NOT EXISTS system_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    level TEXT NOT NULL DEFAULT 'INFO',
    component TEXT NOT NULL DEFAULT '',
    message TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_system_logs_timestamp ON system_logs (timestamp DESC);
