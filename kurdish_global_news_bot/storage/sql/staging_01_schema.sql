-- ----------------------------------------------------------------------------
-- 1. public.articles
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_url TEXT NOT NULL UNIQUE,
    url_hash TEXT NOT NULL DEFAULT '',
    original_url TEXT NOT NULL,
    original_title TEXT NOT NULL DEFAULT '',
    normalized_title TEXT NOT NULL DEFAULT '',
    translated_title TEXT NOT NULL DEFAULT '',
    original_summary TEXT NOT NULL DEFAULT '',
    translated_summary TEXT NOT NULL DEFAULT '',
    source_name TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL DEFAULT '',
    priority TEXT NOT NULL DEFAULT 'NORMAL',
    importance_score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    publication_date TEXT,
    discovered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processed_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'DISCOVERED',
    content_hash TEXT NOT NULL DEFAULT '',
    event_fingerprint TEXT NOT NULL DEFAULT '',
    retry_count INTEGER NOT NULL DEFAULT 0,
    error_message TEXT NOT NULL DEFAULT '',
    telegram_message_id BIGINT,
    thread_root_message_id BIGINT,
    image_url TEXT NOT NULL DEFAULT '',
    video_url TEXT DEFAULT NULL,
    country TEXT NOT NULL DEFAULT '',
    region TEXT NOT NULL DEFAULT '',
    named_entities TEXT NOT NULL DEFAULT '',
    event_key TEXT NOT NULL DEFAULT '',
    event_entities TEXT NOT NULL DEFAULT '',
    is_breaking BOOLEAN NOT NULL DEFAULT FALSE
);

-- Idempotent column guards in case staging project already has an older partial table
ALTER TABLE public.articles ADD COLUMN IF NOT EXISTS url_hash TEXT NOT NULL DEFAULT '';
ALTER TABLE public.articles ADD COLUMN IF NOT EXISTS telegram_message_id BIGINT;
ALTER TABLE public.articles ADD COLUMN IF NOT EXISTS thread_root_message_id BIGINT;
ALTER TABLE public.articles ADD COLUMN IF NOT EXISTS video_url TEXT DEFAULT NULL;
ALTER TABLE public.articles ADD COLUMN IF NOT EXISTS country TEXT NOT NULL DEFAULT '';
ALTER TABLE public.articles ADD COLUMN IF NOT EXISTS region TEXT NOT NULL DEFAULT '';
ALTER TABLE public.articles ADD COLUMN IF NOT EXISTS named_entities TEXT NOT NULL DEFAULT '';
ALTER TABLE public.articles ADD COLUMN IF NOT EXISTS event_key TEXT NOT NULL DEFAULT '';
ALTER TABLE public.articles ADD COLUMN IF NOT EXISTS event_entities TEXT NOT NULL DEFAULT '';
ALTER TABLE public.articles ADD COLUMN IF NOT EXISTS is_breaking BOOLEAN NOT NULL DEFAULT FALSE;

-- Indexes required by deduplication, threading, pacing, watchdog, and RPCs
CREATE INDEX IF NOT EXISTS idx_articles_canonical_url ON public.articles (canonical_url);
CREATE INDEX IF NOT EXISTS idx_articles_url_hash ON public.articles (url_hash);
CREATE INDEX IF NOT EXISTS idx_articles_content_hash ON public.articles (content_hash);
CREATE INDEX IF NOT EXISTS idx_articles_event_fingerprint ON public.articles (event_fingerprint);
CREATE INDEX IF NOT EXISTS idx_articles_status ON public.articles (status);
CREATE INDEX IF NOT EXISTS idx_articles_status_score ON public.articles (status, importance_score DESC);
CREATE INDEX IF NOT EXISTS idx_articles_discovered_at ON public.articles (discovered_at DESC);
CREATE INDEX IF NOT EXISTS idx_articles_published_at ON public.articles (published_at DESC);
CREATE INDEX IF NOT EXISTS idx_articles_published_status_at
    ON public.articles (published_at DESC)
    WHERE status = 'PUBLISHED';
CREATE INDEX IF NOT EXISTS idx_articles_normalized_title ON public.articles (normalized_title);
CREATE INDEX IF NOT EXISTS idx_articles_telegram_message_id ON public.articles (telegram_message_id);
CREATE INDEX IF NOT EXISTS idx_articles_thread_root_message_id ON public.articles (thread_root_message_id);

-- ----------------------------------------------------------------------------
-- 2. public.skipped_urls (low-relevance & duplicate URL hash persistence)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.skipped_urls (
    url_hash TEXT PRIMARY KEY,
    canonical_url TEXT NOT NULL,
    title TEXT NOT NULL DEFAULT '',
    score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    reason TEXT NOT NULL DEFAULT '',
    skipped_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_skipped_urls_canonical ON public.skipped_urls (canonical_url);

-- ----------------------------------------------------------------------------
-- 3. public.daily_digests (prevents duplicate nightly digests per Kurdistan date)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.daily_digests (
    digest_date TEXT PRIMARY KEY,
    story_count INTEGER NOT NULL DEFAULT 0,
    digest_text TEXT NOT NULL DEFAULT '',
    telegram_message_id BIGINT,
    published_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 4. public.sources (source health & failure counters)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    source_type TEXT NOT NULL DEFAULT '',
    url TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL DEFAULT '',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_checked_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    last_error TEXT NOT NULL DEFAULT '',
    consecutive_failures INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_sources_enabled_failures
    ON public.sources (enabled, consecutive_failures DESC, name);

-- ----------------------------------------------------------------------------
-- 5. public.events (event clustering & live threading metadata)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_fingerprint TEXT NOT NULL UNIQUE,
    event_title TEXT NOT NULL DEFAULT '',
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    article_count INTEGER NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS idx_events_fingerprint ON public.events (event_fingerprint);

-- ----------------------------------------------------------------------------
-- 6. public.system_logs (cooldowns, watchdog telemetry, & GLOBAL_RESERVATION ledger)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.system_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    level TEXT NOT NULL DEFAULT 'INFO',
    component TEXT NOT NULL DEFAULT '',
    message TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_system_logs_timestamp ON public.system_logs (timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_system_logs_component_id ON public.system_logs (component, id);
CREATE INDEX IF NOT EXISTS idx_system_logs_component_ts ON public.system_logs (component, timestamp DESC);

-- ----------------------------------------------------------------------------
-- 7. Staging Row Level Security (RLS), Schema Hardening & Least-Privilege Grants
--    The Python bot authenticates as `service_role` (which bypasses RLS).
--    Enabling RLS without permissive policies blocks `anon` / `authenticated`
--    PostgREST access to staging tables by default, and revoking CREATE on
--    `public` prevents untrusted roles from creating shadowing objects.
-- ----------------------------------------------------------------------------
REVOKE CREATE ON SCHEMA public FROM PUBLIC, anon, authenticated;

ALTER TABLE public.articles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.skipped_urls ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_digests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sources ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.system_logs ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.articles FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.skipped_urls FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.daily_digests FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.sources FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.events FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.system_logs FROM PUBLIC, anon, authenticated;

GRANT ALL ON TABLE public.articles TO service_role;
GRANT ALL ON TABLE public.skipped_urls TO service_role;
GRANT ALL ON TABLE public.daily_digests TO service_role;
GRANT ALL ON TABLE public.sources TO service_role;
GRANT ALL ON TABLE public.events TO service_role;
GRANT ALL ON TABLE public.system_logs TO service_role;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
